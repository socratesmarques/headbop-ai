  const supported = ["pt-BR", "en", "es", "fr", "de", "it", "zh-CN", "hi"];
  // Bind a message identity once. User data is never reverse-matched or observed.
  const bindings = new Map();
  function localeOf(value) {
    const input = String(value || "").toLowerCase();
    if (input.startsWith("pt")) return "pt-BR";
    if (input.startsWith("zh")) return "zh-CN";
    return supported.find((code) => input === code || input.startsWith(code + "-")) || "en";
  }
  let stored = null;
  try { stored = window.localStorage.getItem("headbop_language"); } catch (_) { /* Storage is optional. */ }
  let language = localeOf(stored || navigator.language || "pt-BR");
  const has = (key) => Object.prototype.hasOwnProperty.call(translations["pt-BR"], key);
  function t(key, params = {}) {
    if (!has(key)) return translations[language]["error.unknown"];
    const message = translations[language][key];
    if (typeof message !== "string") throw new Error(`Missing translation: ${language}/${key}`);
    return message.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
  }
  function render(node, binding) {
    const value = binding.prefix + t(binding.key, binding.params) + binding.suffix;
    if (binding.attribute) {
      if (node.getAttribute(binding.attribute) !== value) node.setAttribute(binding.attribute, value);
    } else if (node.nodeType === Node.TEXT_NODE) {
      if (node.nodeValue !== value) node.nodeValue = value;
    } else if (node.textContent !== value) node.textContent = value;
  }
  function register(node, attribute, key, params = {}, prefix = "", suffix = "") {
    if (!node) return;
    const entries = bindings.get(node) || new Map();
    const binding = { attribute, key, params: { ...params }, prefix, suffix };
    entries.set(attribute || "text", binding);
    bindings.set(node, entries);
    render(node, binding);
  }
  function unbind(element) {
    if (!element) return;
    for (const node of bindings.keys()) {
      if (node === element || element.contains(node)) bindings.delete(node);
    }
  }
  function bindText(element, key, params = {}) {
    unbind(element);
    register(element, null, key, params);
  }
  function bindAttribute(element, name, key, params = {}) { register(element, name, key, params); }
  function errorMessage(payload = {}) {
    if (!payload || typeof payload !== "object" && typeof payload !== "string") payload = {};
    if (typeof payload === "string") payload = { detail: payload };
    // Keep actionable, known validation instructions instead of hiding them
    // behind a generic validation code; never display untrusted server text.
    if ((!payload.code || payload.code === "invalid_request") && typeof payload.detail === "string" && has(payload.detail)) {
      return { key: payload.detail, params: payload.params || {} };
    }
    const coded = `error.${payload.code || ""}`;
    if (has(coded)) return { key: coded, params: payload.params || {} };
    if (typeof payload.detail === "string" && has(payload.detail)) return { key: payload.detail, params: {} };
    return { key: "error.unknown", params: {} };
  }
  function translateError(payload) { const message = errorMessage(payload); return t(message.key, message.params); }
  function translatePage() {
    document.documentElement.lang = language;
    for (const [node, entries] of bindings) {
      if (!node.isConnected) { bindings.delete(node); continue; }
      for (const binding of entries.values()) render(node, binding);
    }
    const picker = document.getElementById("language-select");
    if (picker) picker.value = language;
  }
  function setLanguage(value) {
    language = localeOf(value);
    try { window.localStorage.setItem("headbop_language", language); } catch (_) { /* Storage is optional. */ }
    translatePage();
    document.dispatchEvent(new CustomEvent("headbop:languagechange", { detail: language }));
  }
  function captureStatic() {
    // New views declare message identities directly. Bind them before walking
    // legacy text nodes, and never infer a key from an already translated value.
    for (const element of document.querySelectorAll("[data-i18n],[data-i18n-aria]")) {
      const textKey = element.getAttribute("data-i18n");
      const ariaKey = element.getAttribute("data-i18n-aria");
      if (textKey) bindText(element, textKey);
      if (ariaKey) bindAttribute(element, "aria-label", ariaKey);
    }
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      if (node.nodeType === Node.TEXT_NODE) {
        if (node.parentElement?.closest("script,style,code,pre,textarea,#language-select,[data-i18n-ignore],[data-i18n]")) continue;
        const original = node.nodeValue || "";
        const key = original.trim();
        if (has(key)) {
          const start = original.indexOf(key);
          register(node, null, key, {}, original.slice(0, start), original.slice(start + key.length));
        }
      } else {
        for (const name of ["aria-label", "aria-valuetext", "title", "placeholder", "alt"]) {
          if (name === "aria-label" && node.hasAttribute("data-i18n-aria")) continue;
          const key = node.getAttribute(name);
          if (key && has(key)) register(node, name, key);
        }
        if (node.tagName === "META" && has(node.getAttribute("content"))) register(node, "content", node.getAttribute("content"));
      }
    }
    translatePage();
  }
